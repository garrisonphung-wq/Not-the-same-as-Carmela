def lookup_pinyin(pinyin_buffer: str, limit: int = 25) -> list[str]:
    """Return ordered Chinese candidates for a romanized pinyin buffer."""
    q = pinyin_buffer.lower().strip()
    if not q:
        return []

    results: list[str] = []
    seen: set[str] = set()

    def _add(items: list[str]) -> None:
        for ch in items:
            if ch not in seen:
                seen.add(ch)
                results.append(ch)
                if len(results) >= limit:
                    return

    # 1. Exact match (also check key+2 for disambiguated keys if needed)
    if q in PINYIN_ENTRIES:
        _add(PINYIN_ENTRIES[q])

    # 2. Longest-prefix segmentation if user typed two syllables together (e.g. "kuaipao" -> "快" + "跑")
    if len(q) >= 3 and len(results) < limit:
        for split_idx in range(len(q) - 1, 0, -1):
            left = q[:split_idx]
            right = q[split_idx:]
            if left in PINYIN_ENTRIES and right in PINYIN_ENTRIES:
                combo = PINYIN_ENTRIES[left][0] + PINYIN_ENTRIES[right][0]
                _add([combo])
                break

    # 3. Prefix matches (e.g. "nih" -> "你好", "kamei" -> "卡梅利多")
    if len(results) < limit:
        prefix_keys = sorted(
            (k for k in PINYIN_ENTRIES if k.startswith(q) and k != q),
            key=lambda k: (len(k), k),
        )
        for pk in prefix_keys:
            _add(PINYIN_ENTRIES[pk])
            if len(results) >= limit:
                break

    return results[:limit]
